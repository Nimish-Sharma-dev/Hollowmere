// Usage: node packages/director/scripts/gen-prompts.ts [--check]
// Extracts the fenced prompt templates from docs/PROMPTS.md into src/prompts.generated.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', '..', '..');
const lines = readFileSync(join(root, 'docs', 'PROMPTS.md'), 'utf8').split('\n');
const blocks: Record<string, string> = {};
let cur: string | null = null;
for (let i = 0; i < lines.length; i++) {
  const l = lines[i]!;
  let m = /^## \d+\. Prompt (P\d)/.exec(l);
  if (m) cur = m[1]!;
  m = /^### 9([ab])\./.exec(l);
  if (m) cur = 'P7' + m[1];
  if (/^`{4,}text/.test(l)) {
    const buf: string[] = [];
    let j = i + 1;
    while (!/^`{4,}\s*$/.test(lines[j]!)) buf.push(lines[j++]!);
    if (cur && !(cur in blocks)) blocks[cur] = buf.join('\n');
    i = j;
  }
}
const order = ['P0', 'P1', 'P2', 'P3', 'P4', 'P5', 'P6', 'P7a', 'P7b', 'P8', 'P9'];
for (const k of order) if (!blocks[k]) throw new Error(`gen-prompts: no template found for ${k}`);
let out = '// GENERATED by scripts/gen-prompts.ts from docs/PROMPTS.md. Do not edit by hand.\nexport const PROMPT_TEXTS: Record<string, string> = {\n';
for (const k of order) out += `  ${k}: ${JSON.stringify(blocks[k])},\n`;
out += '};\n';
const target = join(import.meta.dirname, '..', 'src', 'prompts.generated.ts');
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== out) {
    console.error('prompts.generated.ts is out of date. Run: node packages/director/scripts/gen-prompts.ts');
    process.exit(1);
  }
  console.log('prompts.generated.ts is up to date');
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${order.length} prompts)`);
}
